DROP TABLE IF EXISTS profile_photos CASCADE;
DROP TABLE IF EXISTS user_sessions CASCADE;
DROP TABLE IF EXISTS tags CASCADE;
DROP TABLE IF EXISTS folders CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    role VARCHAR(20) NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_sessions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    refresh_token TEXT NOT NULL UNIQUE,
    device_info JSONB NOT NULL DEFAULT '{}'::jsonb,
    ip_address INET,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX index_user_sessions_user_id
    ON user_sessions(user_id);

CREATE INDEX index_user_sessions_expires_at
    ON user_sessions(expires_at);

CREATE TABLE folders (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id INT REFERENCES folders(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    color VARCHAR(9)
        CHECK (color IS NULL OR color ~ '^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX index_folders_user_id
    ON folders(user_id);

CREATE INDEX index_folders_parent_id
    ON folders(parent_id);

CREATE TABLE tags (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    color VARCHAR(9)
        CHECK (color IS NULL OR color ~ '^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, name)
);

CREATE INDEX index_tags_user_id
    ON tags(user_id);

CREATE TABLE IF NOT EXISTS profile_photos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    original_name VARCHAR(255) NOT NULL,
    storage_key VARCHAR(69) NOT NULL UNIQUE
        CHECK (storage_key ~ '^[a-f0-9]{64}\.webp$'),
    mime_type VARCHAR(30) NOT NULL CHECK (mime_type = 'image/webp'),
    size_bytes INT NOT NULL CHECK (size_bytes BETWEEN 1 AND 2097152),
    width INT NOT NULL CHECK (width BETWEEN 1 AND 512),
    height INT NOT NULL CHECK (height BETWEEN 1 AND 512),
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS index_profile_photos_user ON profile_photos(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS one_current_profile_photo_per_user
    ON profile_photos(user_id) WHERE is_current;
